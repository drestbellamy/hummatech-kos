  final String id;
  final String title;
  final String description;
  final String kostName;
  final DateTime date;
  final String category;
  final String categoryColor;

  Announcement({
    required this.id,
    required this.title,
    required this.description,
    required this.kostName,
    required this.date,
    required this.category,
    required this.categoryColor,
  });
}
